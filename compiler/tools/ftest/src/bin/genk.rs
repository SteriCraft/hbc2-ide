// Generates fmathk.has: constants and tables of exp/log/pow.
use std::fmt::Write;

fn f32bits(v: f64) -> u32 { (v as f32).to_bits() }
fn hex(b: u32) -> String { format!("0x{:08X}", b) }
fn trunc12(v: f64) -> f32 { f32::from_bits((v as f32).to_bits() & 0xFFFF_F000) }

fn addc(c: &mut Vec<(String, u32, String)>, n: &str, v: f64, doc: &str) { c.push((n.to_string(), f32bits(v), doc.to_string())); }

fn main() {
    let mut consts: Vec<(String, u32, String)> = Vec::new();
    addc(&mut consts, "K_ONE", 1.0, "1");
    addc(&mut consts, "K_HALF", 0.5, "1/2");
    addc(&mut consts, "K_1_6", 1.0 / 6.0, "1/6");
    addc(&mut consts, "K_1_32", 1.0 / 32.0, "1/32");
    addc(&mut consts, "K_32", 32.0, "32");
    addc(&mut consts, "K_2P24", 16777216.0, "2^24");
    addc(&mut consts, "K_LN2", std::f64::consts::LN_2, "ln 2");
    addc(&mut consts, "K_1_5", 0.2, "1/5");
    addc(&mut consts, "K_M1_6", -1.0 / 6.0, "-1/6");
    addc(&mut consts, "K_M1_4", -0.25, "-1/4");
    addc(&mut consts, "K_1_3", 1.0 / 3.0, "1/3");
    addc(&mut consts, "K_M1_2", -0.5, "-1/2");
    addc(&mut consts, "K_P129", 129.0, "129");
    addc(&mut consts, "K_N152", -152.0, "-152");
    addc(&mut consts, "K_MONE", -1.0, "-1");
    let split = |n: &str, v: f64, doc: &str, consts: &mut Vec<(String, u32, String)>| {
        let hi = trunc12(v);
        let lo = (v - hi as f64) as f32;
        consts.push((format!("{n}_1"), hi.to_bits(), format!("{doc}, high part (12 bits)")));
        consts.push((format!("{n}_2"), lo.to_bits(), format!("{doc}, the rest")));
        consts.push((format!("{n}_F"), f32bits(v), format!("{doc}, as one float")));
    };
    split("K_L2E", std::f64::consts::LOG2_E, "log2 e", &mut consts);
    split("K_L210", std::f64::consts::LOG2_10, "log2 10", &mut consts);
    split("K_LN2S", std::f64::consts::LN_2, "ln 2", &mut consts);
    split("K_LG2", std::f64::consts::LOG10_2, "log10 2", &mut consts);

    // trig
    addc(&mut consts, "K_ZERO", 0.0, "0");
    addc(&mut consts, "K_TWO", 2.0, "2");
    addc(&mut consts, "K_S1", 1.0 / 120.0, "1/120");
    addc(&mut consts, "K_S2", -1.0 / 5040.0, "-1/5040");
    addc(&mut consts, "K_S3", 1.0 / 362880.0, "1/362880");
    addc(&mut consts, "K_S4", -1.0 / 39916800.0, "-1/39916800");
    addc(&mut consts, "K_C0", 1.0 / 24.0, "1/24");
    addc(&mut consts, "K_C1", -1.0 / 720.0, "-1/720");
    addc(&mut consts, "K_C2", 1.0 / 40320.0, "1/40320");
    addc(&mut consts, "K_C3", -1.0 / 3628800.0, "-1/3628800");
    addc(&mut consts, "K_C4", 1.0 / 479001600.0, "1/479001600");
    addc(&mut consts, "K_PIO4", std::f64::consts::FRAC_PI_4, "pi/4");
    addc(&mut consts, "K_16", 16.0, "16");
    addc(&mut consts, "K_6", 6.0, "6");
    addc(&mut consts, "K_INF", f64::INFINITY, "infinity");
    addc(&mut consts, "K_E720", 1.0 / 720.0, "1/720");
    addc(&mut consts, "K_E5040", 1.0 / 5040.0, "1/5040");
    addc(&mut consts, "K_E3M", 1.0 / 3628800.0, "1/3628800");
    addc(&mut consts, "K_N18", -18.0, "-18");
    addc(&mut consts, "K_0_35", 0.35, "0.35");
    addc(&mut consts, "K_EMMAX", 88.72284, "88.72284 (exp overflows from there)");
    addc(&mut consts, "K_SHMAX", 129.0 * std::f64::consts::LN_2, "129 ln 2 (sinh, cosh overflow from there)");
    addc(&mut consts, "K_9_1", 9.1, "9.1");
    addc(&mut consts, "K_QUARTER", 0.25, "1/4");
    addc(&mut consts, "K_8192", 8192.0, "2^13");
    addc(&mut consts, "K_3", 3.0, "3");
    addc(&mut consts, "K_1P5", 1.5, "1.5");
    addc(&mut consts, "K_1_7", 1.0 / 7.0, "1/7");
    addc(&mut consts, "K_M1_5", -0.2, "-1/5");
    addc(&mut consts, "K_PIO2_F", std::f64::consts::FRAC_PI_2, "pi/2, as one float");
    addc(&mut consts, "K_PIO2_L", std::f64::consts::FRAC_PI_2 - (std::f64::consts::FRAC_PI_2 as f32) as f64, "pi/2 minus the float");
    addc(&mut consts, "K_PI_F", std::f64::consts::PI, "pi, as one float");
    addc(&mut consts, "K_3PIO4", 3.0 * std::f64::consts::FRAC_PI_4, "3 pi/4, as one float");
    {
        let p = std::f64::consts::FRAC_PI_2;
        let p1 = trunc12(p);
        let r1 = p - p1 as f64;
        let p2 = trunc12(r1);
        let p3 = (r1 - p2 as f64) as f32;
        consts.push(("K_PIO2_1".into(), p1.to_bits(), "pi/2, first 12 bits".into()));
        consts.push(("K_PIO2_2".into(), p2.to_bits(), "pi/2, next 12 bits".into()));
        consts.push(("K_PIO2_3".into(), p3.to_bits(), "pi/2, the rest".into()));
    }

    let mut s = String::new();
    writeln!(s, "; GENERATED by genk.rs (constants computed with f64, rounded to binary32). Do not edit.").unwrap();
    writeln!(s, "; Offsets of the constants in fx_k (K_*), used by the fx_*c helpers (fx.has).").unwrap();
    for (i, (n, _, d)) in consts.iter().enumerate() {
        writeln!(s, ".define {:<9} {:<4} ; {}", n, i * 4, d).unwrap();
    }
    let vals: Vec<String> = consts.iter().map(|c| hex(c.1)).collect();
    writeln!(s, ".data32 fx_k {}", vals.join(", ")).unwrap();

    // 2^(j/32), j = -16..16: hi, lo
    writeln!(s, "\n; fx_t2[j + 16] = 2^(j/32), j = -16..16: 8 bytes each, high float then low float.").unwrap();
    let mut v = Vec::new();
    for j in -16i32..=16 {
        let x = (j as f64 / 32.0).exp2();
        let hi = x as f32;
        let lo = (x - hi as f64) as f32;
        v.push(hex(hi.to_bits()));
        v.push(hex(lo.to_bits()));
    }
    writeln!(s, ".data32 fx_t2 {}", v.join(", ")).unwrap();

    // c = 1 + j/32, log2 c: c, high (16 fraction bits), low; j = 0..32
    writeln!(s, "\n; fx_tl[j] (j = 0..32), 12 bytes each: c = 1 + j/32, log2 c truncated to 16 bits, the rest.").unwrap();
    let mut v = Vec::new();
    for j in 0..=32 {
        let c = 1.0 + j as f64 / 32.0;
        let l = c.log2();
        let hi = (l * 65536.0).floor() / 65536.0;
        let lo = (l - hi) as f32;
        v.push(hex((c as f32).to_bits()));
        v.push(hex((hi as f32).to_bits()));
        v.push(hex(lo.to_bits()));
    }
    writeln!(s, ".data32 fx_tl {}", v.join(", ")).unwrap();
    // atan: c = j/16, atan c high, low; j = 0..16
    writeln!(s, "
; fx_ta[j] (j = 0..16), 12 bytes each: c = j/16, atan c as a float, the rest.").unwrap();
    let mut v = Vec::new();
    for j in 0..=16 {
        let c = j as f64 / 16.0;
        let a = c.atan();
        let hi = a as f32;
        let lo = (a - hi as f64) as f32;
        v.push(hex((c as f32).to_bits()));
        v.push(hex(hi.to_bits()));
        v.push(hex(lo.to_bits()));
    }
    writeln!(s, ".data32 fx_ta {}", v.join(", ")).unwrap();

    // 2/pi bytes for the Payne-Hanek reduction: 4 zero bytes, then B_1..B_32
    let bytes = two_over_pi_bytes(32);
    writeln!(s, "
; ft_2pi: 4 zero bytes, then the first 32 bytes of the binary expansion of 2/pi (A2 F9 83 6E ...).").unwrap();
    let mut v: Vec<String> = vec!["0".into(); 4];
    for b in &bytes { v.push(format!("0x{:02X}", b)); }
    writeln!(s, ".data ft_2pi {}", v.join(", ")).unwrap();
    let out = std::env::args().nth(1).unwrap_or_else(|| concat!(env!("CARGO_MANIFEST_DIR"), "/../../lib/asm/math/float/fmathk.has").to_string());
    std::fs::write(out, s).unwrap();
}

// ---- tiny big-integer code (little-endian u32 limbs) to get 2/pi exactly
type Big = Vec<u32>;
const LIMBS: usize = 80;
fn big_from(v: u32) -> Big { let mut b = vec![0u32; LIMBS]; b[0] = v; b }
fn big_shl(a: &Big, n: usize) -> Big {
    let mut r = vec![0u32; LIMBS];
    let (w, bit) = (n / 32, n % 32);
    for i in (0..LIMBS).rev() {
        if i < w { continue; }
        let mut v = (a[i - w] as u64) << bit;
        if bit > 0 && i - w >= 1 { v |= (a[i - w - 1] as u64) >> (32 - bit); }
        r[i] = v as u32;
    }
    r
}
fn big_add(a: &Big, b: &Big) -> Big {
    let mut r = vec![0u32; LIMBS]; let mut c = 0u64;
    for i in 0..LIMBS { let s = a[i] as u64 + b[i] as u64 + c; r[i] = s as u32; c = s >> 32; }
    r
}
fn big_sub(a: &Big, b: &Big) -> Big {
    let mut r = vec![0u32; LIMBS]; let mut br = 0i64;
    for i in 0..LIMBS { let mut s = a[i] as i64 - b[i] as i64 - br; if s < 0 { s += 1 << 32; br = 1; } else { br = 0; } r[i] = s as u32; }
    r
}
fn big_cmp(a: &Big, b: &Big) -> std::cmp::Ordering {
    for i in (0..LIMBS).rev() { if a[i] != b[i] { return a[i].cmp(&b[i]); } }
    std::cmp::Ordering::Equal
}
fn big_div_small(a: &Big, d: u32) -> Big {
    let mut r = vec![0u32; LIMBS]; let mut rem = 0u64;
    for i in (0..LIMBS).rev() { let cur = (rem << 32) | a[i] as u64; r[i] = (cur / d as u64) as u32; rem = cur % d as u64; }
    r
}
fn big_is_zero(a: &Big) -> bool { a.iter().all(|&x| x == 0) }
fn big_mul_small(a: &Big, m: u32) -> Big {
    let mut r = vec![0u32; LIMBS]; let mut c = 0u64;
    for i in 0..LIMBS { let s = a[i] as u64 * m as u64 + c; r[i] = s as u32; c = s >> 32; }
    r
}
fn atan_inv(n: u32, scale: &Big) -> Big {
    let mut term = big_div_small(scale, n);
    let mut sum = term.clone();
    let mut k = 1u32;
    let mut neg = true;
    while !big_is_zero(&term) {
        term = big_div_small(&term, n * n);
        let t = big_div_small(&term, 2 * k + 1);
        sum = if neg { big_sub(&sum, &t) } else { big_add(&sum, &t) };
        neg = !neg; k += 1;
    }
    sum
}
fn two_over_pi_bytes(count: usize) -> Vec<u8> {
    let fb = 1000usize; // fraction bits of the fixed point numbers
    let scale = big_shl(&big_from(1), fb);
    let pi = big_sub(&big_mul_small(&atan_inv(5, &scale), 16), &big_mul_small(&atan_inv(239, &scale), 4));
    // q = floor(2 * 2^fb * 2^fb / pi) : bit-serial long division
    let num = big_shl(&big_from(1), 2 * fb + 1);
    let mut rem = vec![0u32; LIMBS];
    let mut q = vec![0u32; LIMBS];
    for bit in (0..=(2 * fb + 1)).rev() {
        rem = big_shl(&rem, 1);
        if (num[bit / 32] >> (bit % 32)) & 1 == 1 { rem[0] |= 1; }
        if big_cmp(&rem, &pi) != std::cmp::Ordering::Less { rem = big_sub(&rem, &pi); q[bit / 32] |= 1 << (bit % 32); }
    }
    // q = (2/pi) * 2^fb. Byte m (m >= 1) = (q >> (fb - 8 m)) & 0xFF
    (1..=count).map(|m| { let sh = fb - 8 * m; ((q[sh / 32] >> (sh % 32)) & 0xFF) as u8 }).collect()
}
