/* buf must be s, and r its length */
static void is(int r, const char *s)
{
    check(r == (int)strlen(s) && strcmp(buf, s) == 0);
}

static void scan(const char *s, const char *fmt, unsigned long v, int k)
{
    float f = 0;
    int m = -1;
    check(sscanf(s, fmt, &f, &m) == 1 && bits(f) == v && m == k);
}

int main(void)
{
    int i, r;
    float f, g;
    char s[8];

    /* 1-723: the table */
    for (i = 0; i < sizeof outs / sizeof outs[0]; i++)
        is(sprintf(buf, fmts[outs[i].f], fb(outs[i].v)), outs[i].s);

    /* the integer flags and precision */
    is(sprintf(buf, "%.3d|%5.3d|%+d|% d|%+d", 7, -7, 5, 5, -5), "007| -007|+5| 5|-5");
    is(sprintf(buf, "[%.0d][%5.0d][%-+6d]", 0, 0, 42), "[][     ][+42   ]");
    is(sprintf(buf, "%*d|%-*d|%*d|", 4, 7, 4, 7, -4, 7), "   7|7   |7   |");
    is(sprintf(buf, "%.*s|%.10s|%i|%hd", 3, "abcdef", "ab", -12, 5), "abc|ab|-12|5");
    is(sprintf(buf, "%08.3d|%.5x|%+u|%.3ld|%.0d", 5, 0xAB, 5, 5L, 3), "     005|000ab|5|005|3");
    r = sprintf(buf, "%.300d", -1);
    check(r == 301 && buf[0] == '-' && buf[1] == '0' && buf[299] == '0' && buf[300] == '1' && buf[301] == 0);

    /* floats: * for the width and the precision, padding, special values */
    is(sprintf(buf, "%*.*f|%.*e", 8, 2, 1.5f, -1, 1.5f), "    1.50|1.500000e+00");
    is(sprintf(buf, "%-08.2f|%08.2f|%+08.2e", -1.5f, -1.5f, 1.5f), "-1.50   |-0001.50|+1.50e+00");
    is(sprintf(buf, "%010f|%-6f|%06F|%+f", fb(0x7F800000UL), fb(0x7FC00000UL), fb(0xFF800000UL), fb(0x7F800000UL)),
       "       inf|nan   |  -INF|+inf");
    is(sprintf(buf, "%#.0e|%#.0f|%#.0g|%#5.1g", 1.0f, 2.0f, 3.0f, 0.0f), "1.e+00|2.|3.|   0.");
    is(sprintf(buf, "%lf %Lf %le %lg", 0.5f, 0.25f, 2.0f, 3.0f), "0.500000 0.250000 2.000000e+00 3");
    is(sprintf(buf, "%.0f %.0f %.0f %.0f %.1f %.2f", 0.5f, 1.5f, 2.5f, 3.5f, 0.25f, 1.005f), "0 2 2 4 0.2 1.00");
    is(sprintf(buf, "%g %g %g %g", 0.0001f, 123456.0f, 1234567.0f, 0.00001f), "0.0001 123456 1.23457e+06 1e-05");
    is(sprintf(buf, "%.0e %.1e %g", 9.5f, 9.96f, 999999.5f), "1e+01 1.0e+01 1e+06");
    is(sprintf(buf, "%5.1f%%|%c%s", 99.95f, 'x', "y"), " 99.9%|xy");

    /* more than 192 digits: the zeros are counted, not written */
    r = sprintf(buf, "%.300f", 1.0f);
    check(r == 302 && buf[0] == '1' && buf[1] == '.' && buf[2] == '0' && buf[301] == '0' && buf[302] == 0);
    r = sprintf(buf, "%.200e", fb(0x3EAAAAABUL));
    check(r == 206 && strncmp(buf, "3.333333432674407958984375000", 29) == 0
          && strcmp(buf + 198, "0000e-01") == 0);
    r = sprintf(buf, "%#.250g", 0.5f);
    check(r == 252 && strncmp(buf, "0.5000", 6) == 0 && buf[251] == '0');
    r = sprintf(buf, "%-12.149f|", fb(1));
    check(r == 152 && strncmp(buf, "0.000000000000000000000000000000000000000000001401298", 53) == 0
          && strcmp(buf + 145, "203125|") == 0);
    r = sprintf(buf, "%.0f", fb(0x7F7FFFFFUL));
    check(r == 39 && strcmp(buf, "340282346638528859811704183484516925440") == 0);
    r = printf("");
    check(r == 0);

    /* scanf: every input of ins, with %f %e %g %E %lf */
    for (i = 0; i < sizeof ins / sizeof ins[0]; i++) {
        scan(ins[i].s, "%f%n", ins[i].v, ins[i].n);
#ifndef HOST
        scan(ins[i].s, "%le%n", ins[i].v, ins[i].n);
        scan(ins[i].s, "%Lg%n", ins[i].v, ins[i].n);
#endif
        scan(ins[i].s, "%E%n", ins[i].v, ins[i].n);
    }
    f = g = 7;
    check(sscanf("12345", "%3f%f", &f, &g) == 2 && f == 123 && g == 45);
    check(sscanf("1.5 2.5", "%*f %f", &f) == 1 && f == 2.5f);
    check(sscanf("abc", "%f", &f) == 0 && sscanf("", "%f", &f) == EOF);
    check(sscanf("-", "%f", &f) == 0 && sscanf(".", "%f", &f) == 0 && sscanf("e5", "%f", &f) == 0);
    check(sscanf("+.e1", "%f", &f) == 0 && sscanf("in", "%f", &f) == 0 && f == 2.5f);
    check(sscanf("12 .5x", "%d%f%s", &i, &f, s) == 3 && i == 12 && f == 0.5f && strcmp(s, "x") == 0);
    check(sscanf("1e+x", "%f%s", &f, s) == 2 && f == 1 && strcmp(s, "x") == 0);
    check(sscanf("1234567890123456789012345678901234567890", "%f", &f) == 1 && bits(f) == 0x7F800000UL);
    check(sscanf("12345678901234567890123456789012345678901", "%f", &f) == 0);
    check(sscanf("  -1.5e-3,7", "%g,%d", &f, &i) == 2 && f == -1.5e-3f && i == 7);

    return fail;
}
