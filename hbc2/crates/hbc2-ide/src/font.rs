/// The glyph of an ASCII code, or `None` for a non-displayable code (drawn as a blank cell).
pub fn glyph(ascii: u8) -> Option<&'static [u8; CHAR_HEIGHT]> {
    GLYPHS.get(ascii.checked_sub(FIRST_DISPLAYABLE_CHAR)? as usize)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_and_space() {
        assert_eq!(glyph(b' '), Some(&[0; 8]));
        assert_eq!(glyph(b'A').unwrap()[1], 0b011100);
        assert_eq!(glyph(0x1F), None);
        assert_eq!(glyph(0x7F), None);
    }
}
